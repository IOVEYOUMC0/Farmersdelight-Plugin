"""Check the block/item behaviour option keys the code reads against a checked-in manifest.

Why this matters: a behaviour option the code never reads is silently ignored by CraftEngine, so the operator
sees a feature that falls back to its default. `BehaviorArgDiagnostics` warns about that at runtime, but the
runtime warning can only fire for options somebody actually wrote into a pack; this check keeps the documented
set and the code reading it in step, so a rename cannot leave the manifest (and the docs generated from it)
describing keys nothing reads any more.

What it checks:
  * every `BehaviorArgParser` / `BehaviorArguments` literal key read from `src/main/java`, grouped by the source
    file that reads it;
  * that the manifest at tools/behavior-keys.txt matches that set in both directions;
  * when a wiki checkout is reachable (../FarmersdelightPluginWiKi or wiki/), that every key appears in the wiki
    documentation. Missing wiki entries are reported as warnings, not failures, because the wiki is a separate
    repository this check cannot require.

Usage:
    python tools/check_behavior_keys.py            # from FarmersDelight/
    python tools/check_behavior_keys.py --quiet
    python tools/check_behavior_keys.py --update   # rewrite the manifest from the current code
Exit code 0 when clean, 1 when the manifest and the code disagree.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
REPO = TOOLS.parent
MANIFEST = TOOLS / "behavior-keys.txt"
SOURCE_ROOTS = [REPO / "src/main/java", REPO / "src/debugTools/java"]

# `BehaviorArgParser.getInt(arguments, "open-while-sneaking")` and
# `BehaviorArguments.raw(arguments, "burn.enabled")` both spell the key as the second literal argument.
READ = re.compile(
    r"BehaviorArg(?:Parser|uments)\.\w+\s*\(\s*[^,]+,\s*\"([^\"]+)\""
)
# `BehaviorArguments.rawWithLegacy(arguments, "bone-meal.age-bonus", "bone_meal_age_bonus")`.
LEGACY = re.compile(
    r"BehaviorArg(?:Parser|uments)\.(?:getRaw|rawWithLegacy)\s*\(\s*[^,]+,\s*\"([^\"]+)\"\s*,\s*\"([^\"]+)\""
)
WIKI_ROOTS = [REPO.parent / "FarmersdelightPluginWiKi", REPO / "wiki"]

HEADER = """# Behaviour option keys read from code, one source file per line: `<file>: <key>, <key>, ...`
# Generated by tools/check_behavior_keys.py --update; the check fails when the code and this file disagree.
"""


def top_level(key: str) -> str:
    return key.split(".", 1)[0]


def scan() -> dict[str, set[str]]:
    found: dict[str, set[str]] = {}
    for root in SOURCE_ROOTS:
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*.java")):
            text = path.read_text(encoding="utf-8", errors="replace")
            keys: set[str] = set()
            for match in READ.finditer(text):
                keys.add(top_level(match.group(1)))
            for match in LEGACY.finditer(text):
                keys.add(top_level(match.group(1)))
                keys.add(match.group(2))
            if keys:
                found.setdefault(path.name, set()).update(keys)
    return found


def render(found: dict[str, set[str]]) -> str:
    lines = [HEADER.rstrip("\n")]
    for name in sorted(found):
        lines.append(f"{name}: {', '.join(sorted(found[name]))}")
    return "\n".join(lines) + "\n"


def parse_manifest(text: str) -> dict[str, set[str]]:
    entries: dict[str, set[str]] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        name, _, rest = line.partition(":")
        entries.setdefault(name.strip(), set()).update(
            part.strip() for part in rest.split(",") if part.strip()
        )
    return entries


def wiki_files() -> list[Path]:
    for root in WIKI_ROOTS:
        if root.is_dir():
            return [path for path in root.rglob("*") if path.suffix in (".md", ".mdx")]
    return []


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--quiet", action="store_true")
    parser.add_argument("--update", action="store_true", help="rewrite the manifest from the current code")
    args = parser.parse_args()

    found = scan()
    if not found:
        print("no behaviour option reads found; the scanner is out of date with the code")
        return 1

    rendered = render(found)
    if args.update:
        MANIFEST.write_text(rendered, encoding="utf-8", newline="\n")
        if not args.quiet:
            print(f"behaviour keys: wrote {sum(len(keys) for keys in found.values())} keys "
                  f"across {len(found)} files to {MANIFEST.name}")
        return 0

    if not MANIFEST.is_file():
        print(f"missing manifest {MANIFEST}; run: python tools/check_behavior_keys.py --update")
        return 1
    expected = parse_manifest(MANIFEST.read_text(encoding="utf-8"))

    problems: list[str] = []
    for name in sorted(set(expected) | set(found)):
        want = expected.get(name, set())
        have = found.get(name, set())
        for key in sorted(want - have):
            problems.append(f"{name}: manifest lists '{key}' but the code does not read it")
        for key in sorted(have - want):
            problems.append(f"{name}: code reads '{key}' but the manifest does not list it")

    wiki = wiki_files()
    missing_docs: list[str] = []
    if wiki:
        texts = [path.read_text(encoding="utf-8", errors="replace") for path in wiki]
        for key in sorted({key for keys in found.values() for key in keys}):
            if not any(key in text for text in texts):
                missing_docs.append(key)

    if problems:
        for line in problems:
            print(line)
        print(f"problems: {len(problems)}")
        return 1

    if not args.quiet:
        total = sum(len(keys) for keys in found.values())
        print(f"behaviour keys: {total} keys across {len(found)} files match the manifest")
        if wiki:
            for key in missing_docs:
                print(f"warning: '{key}' is read by the code but not mentioned in the wiki")
    return 0


if __name__ == "__main__":
    sys.exit(main())
